#!/usr/bin/env node
// Generates src/contracts/generated-constants.ts (arch step 2, S0).
//
// The two SHAs a service publishes on its health endpoint have to come from
// somewhere authoritative, or every lane invents its own definition and the
// fields become decorative — the exact failure mode S0 exists to prevent.
// They come from here.
//
//   SCHEMA_SHA            sha256 over `<name>@<version>` plus every published
//                         json-schema/*.json file (name + bytes, sorted). Changes
//                         whenever the published wire contract changes, including
//                         a same-version re-publish.
//   CONTRACT_MANIFEST_SHA sha256 of contracts/adoption-manifest.json, as recorded
//                         by scripts/check-adoption-manifest.mjs --write-sha.
//
// Default mode VERIFIES and exits 1 when stale. `--write` regenerates.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/contracts/generated-constants.ts');
const shaArgIndex = process.argv.indexOf('--sha-file');
const SHA_FILE =
  shaArgIndex !== -1 && process.argv[shaArgIndex + 1]
    ? resolve(process.argv[shaArgIndex + 1])
    : join(ROOT, 'contracts/manifest.sha256');

const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));

const h = createHash('sha256');
h.update(`${pkg.name}@${pkg.version}\n`);
for (const file of readdirSync(join(ROOT, 'json-schema')).filter((f) => f.endsWith('.json')).sort()) {
  h.update(file);
  h.update(readFileSync(join(ROOT, 'json-schema', file)));
}
const schemaSha = h.digest('hex');

if (!existsSync(SHA_FILE)) {
  console.error(`contract-constants: FAIL contracts/manifest.sha256 missing — run check-adoption-manifest.mjs --write-sha first`);
  process.exit(1);
}
const contractManifestSha = readFileSync(SHA_FILE, 'utf8').trim();

const body = `// GENERATED by scripts/generate-contract-constants.mjs — do not edit by hand.
// Regenerate with: npm run generate:contract-constants
//
// See ./health-manifest.ts for what these are and where they go.

/** sha256 of the published wire contract (package name+version + every json-schema/*.json). */
export const SCHEMA_SHA = '${schemaSha}';

/** sha256 of contracts/adoption-manifest.json. */
export const CONTRACT_MANIFEST_SHA = '${contractManifestSha}';

/** The exact @talchain/schemas version these constants were generated from. */
export const SCHEMA_PACKAGE_VERSION = '${pkg.version}';
`;

if (process.argv.includes('--write')) {
  writeFileSync(OUT, body);
  console.log(`contract-constants: wrote ${OUT}`);
  console.log(`contract-constants: SCHEMA_SHA=${schemaSha}`);
  console.log(`contract-constants: CONTRACT_MANIFEST_SHA=${contractManifestSha}`);
  process.exit(0);
}

if (!existsSync(OUT)) {
  console.error('contract-constants: FAIL src/contracts/generated-constants.ts missing — run with --write');
  process.exit(1);
}
if (readFileSync(OUT, 'utf8') !== body) {
  console.error(
    'contract-constants: FAIL src/contracts/generated-constants.ts is STALE.\n' +
      `  expected SCHEMA_SHA=${schemaSha}\n` +
      `  expected CONTRACT_MANIFEST_SHA=${contractManifestSha}\n` +
      '  run: npm run generate:contract-constants',
  );
  process.exit(1);
}
console.log('contract-constants: OK (generated-constants.ts is current)');
